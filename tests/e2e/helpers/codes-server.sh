# Поля последней записи цепочки выдач, по одному `ключ=значение` на строку.
#
# Читает их продукт (`issuer codes record show`), а не sed: грант лежит в строке
# цепочки шестнадцатеричным полем, а запрос внутри гранта — снова
# шестнадцатеричным, и разбор текстовым инструментом был бы вторым читателем
# формата, написанным на sed. Он бы не «ошибался иногда» — он бы не работал
# вовсе, и кейс падал бы как сбой стенда.
last_record_fields() {
    [ -s "$SERVER_CHAIN" ] || die \
        "нет цепочки выдач $SERVER_CHAIN: её пишет служба выдачи, которая подписывает грант, \
а на этом стенде её ещё нет — см. tests/e2e/BASELINE.md"
    command -v issuer >/dev/null 2>&1 || die "не найден issuer — разобрать запись выдачи нечем"

    local last="$RUN_DIR/last-record.ndjson"
    tail -1 "$SERVER_CHAIN" > "$last"
    issuer codes record show --record "$last" \
        || die "issuer codes record show не разобрал последнюю запись цепочки"
}

