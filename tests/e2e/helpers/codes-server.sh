            ;;
    esac
}

# Личный номер с неверным контрольным символом не порождает challenge.
#
# Норма ENG-010 требует от УСТРОЙСТВА отвергать номер, чей контрольный символ не
# сходится, — и отвергать до порождения challenge. Разница наблюдаема и стоит
# дорого: опечатка в номере иначе даёт код, который «почти сошёлся», и её
# отлаживают на объекте, глядя на арифметику вместо строки, которую человек
# набрал не так.
#
# Проверяемое здесь — отсутствие challenge, а не текст промпта: текст переводится
# и переписывается, а порождённый challenge на неверный номер означает попытку,
# которой не должно было быть, и nonce, потраченный впустую.
cmd_expect_personal_number_refused() {
    local user="${1:-}"
    [ -n "$user" ] || usage_error "usage: codes-server.sh expect-personal-number-refused <user>"

    load_prepared
    install -d -m 0700 "$RUN_DIR"
    local fifo="$RUN_DIR/conv.in" out="$RUN_DIR/conv.out" err="$RUN_DIR/conv.err"
    rm -f "$fifo" "$out" "$err"
    mkfifo -m 0600 "$fifo"

    # Номер той же формы, что настоящий, с испорченным последним знаком: кейс
    # проверяет контрольный символ, а не длину и не алфавит.
    local wrong="${ENGINEER_ID%?}"
    case "${ENGINEER_ID: -1}" in
        4) wrong="${wrong}5" ;;
        *) wrong="${wrong}4" ;;
    esac
    [ "$wrong" != "$ENGINEER_ID" ] || die "порча номера не изменила его — хелпер сломан"

    pam-drive --answers-per-prompt "$PAM_SERVICE_NAME" "$user" authenticate \
        < "$fifo" > "$out" 2> "$err" &
    DRIVER_PID=$!

    exec 3> "$fifo"
    printf '%s\n' "$SERVER_ID" >&3
    printf '%s\n' "$wrong" >&3
    printf '%s\n' "$DEVICE_KEY_PIN" >&3
    # Разговор не продолжаем: если устройство всё же спросит код, отвечать ему
    # нечем и незачем — challenge, которого не должно было быть, уже показан.
    exec 3>&-

    local waited=0 limit="${TESSERA_E2E_CHALLENGE_TIMEOUT:-30}"
    while kill -0 "$DRIVER_PID" 2>/dev/null && [ "$waited" -lt "$limit" ]; do
        sleep 0.2
        waited=$((waited + 1))
    done
    kill "$DRIVER_PID" 2>/dev/null || true
    wait "$DRIVER_PID" 2>/dev/null || true
    DRIVER_PID=""
    rm -f "$fifo"

    if grep -q -E 'tessera-codes/v1/signed-challenge;' "$err" 2>/dev/null; then
        echo "codes-server: устройство породило challenge на номер $wrong" >&2
        return 1
    fi
    echo "личный номер $wrong отвергнут, challenge не порождён"
}

# Номер устройства с переставленными соседями не доходит до вычислений.
#
# Контрольный символ номера существует ровно ради этого: номер, переписанный с
# этикетки с перепутанными соседними знаками, обязан быть отвергнут КАК НОМЕР, а
# не пройти дальше и получить отказ по подписи или по реестру. Разница видна
# снаружи и стоит дорого: первый ответ говорит «вы ошиблись, переписывая номер»,
# второй — «устройство вам не доверяет», и второй уводит разбор в другую сторону.
#
# Проверяются ВСЕ соседние пары буквенно-цифровых знаков тела номера, а не одна
# выбранная: гарантия сформулирована про любую перестановку, и кейс на одной паре
# подтверждал бы её одним примером.
#
# Запрос инженера собирается вокруг ИСХОДНОГО challenge, а предъявляется
# перебитый. Иначе собирать запрос было бы не из чего: инструмент стенда сам
# разбирает challenge и упал бы раньше выдачи — кейс сообщал бы о сбое стенда
# там, где продукт как раз ответил правильно.
cmd_expect_transposed_number_refused() {
    local user="${1:-}"
    [ -n "$user" ] || usage_error "usage: codes-server.sh expect-transposed-number-refused <user>"

    load_prepared
    capture_challenge "$user"

    local wire number body check
    wire="$(cat "$CHALLENGE_FILE")"
    number="$(field_value "$wire" device)"
    [ ${#number} -ge 3 ] || die "номер устройства $number короче трёх знаков — переставлять нечего"
    body="${number%?}"
    check="${number#"$body"}"

    local checked=0 position=1
    while [ "$position" -lt "${#body}" ]; do
        local left right head tail swapped
        left="$(printf '%s' "$body" | cut -c "$position")"
        right="$(printf '%s' "$body" | cut -c "$((position + 1))")"
        # `cut -c 1-0` — ошибка, а не пустая строка, поэтому первая пара
        # обрабатывается без вырезания головы.
        if [ "$position" -eq 1 ]; then head=""; else
            head="$(printf '%s' "$body" | cut -c "1-$((position - 1))")"
        fi
        tail="$(printf '%s' "$body" | cut -c "$((position + 2))-")"
        position=$((position + 1))
        # Разделители номера не переставляются: перенос дефиса даёт номер другой
        # ФОРМЫ, и отказ по форме не сказал бы ничего о контрольном символе.
        case "$left$right" in
            *[!0-9A-Za-z]*) continue ;;
        esac
        [ "$left" != "$right" ] || continue

        swapped="$head$right$left$tail$check"
        [ "$swapped" != "$number" ] || die "перестановка не изменила номер $number — хелпер сломан"

        local err="$RUN_DIR/issue-transposed.err" rc=0 class
        run_issue "$err" "$(replace_field "$wire" device "$swapped")" "$DEFAULT_GROUNDS" "$wire" \
            > /dev/null || rc=$?
        if [ "$rc" -eq 0 ]; then
            echo "codes-server: выдача посчитала код по номеру $swapped вместо $number" >&2
            return 1
        fi
        class="$(issue_refusal_class "$err")"
        if [ "$class" != challenge_malformed ]; then
            cat "$err" >&2
            die "номер $swapped отвергнут классом $class, а не challenge_malformed — контрольный \
символ эту перестановку не поймал, и отказ пришёл по другой причине"
        fi
        checked=$((checked + 1))
    done

    [ "$checked" -gt 0 ] || die \
        "в номере $number не нашлось ни одной соседней буквенно-цифровой пары — проверять нечего"
    echo "перестановок отвергнуто как challenge_malformed: $checked"
}

