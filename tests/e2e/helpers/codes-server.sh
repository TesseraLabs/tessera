# Устройство показывает challenge проводной формой контракта — одной строкой
# `tessera-codes/v1/signed-challenge;device=…;signature=…`. Ровно эта строка едет
# во фрагмент URL и в QR, и ровно её читает сторона инженера, поэтому хелпер
# берёт её как есть и ничего не собирает заново: своё написание формата
# разошлось бы с продуктом молча.
#
# ВАЖНО про перебивку полей ниже: подпись устройства покрывает все восемь полей,
# поэтому challenge с перебитым полем выдача отвергает по подписи. Своей подписи
# у хелпера нет и быть не может — канонические байты сообщения собирает крейт
# контракта. Перебивка поэтому годится ровно там, где проверяется отказ,
# наступающий РАНЬШЕ проверки подписи (рамки билета), или сам отказ по подписи.
#
# Второй аргумент — уровень, которым перебивается полученное поле. Он нужен
# ровно одному кейсу: проверке, что выдача не считает код за пределами рамок
# билета. Метку процесса на системе без мандатного механизма не поднять, а для
# выдачи challenge — это строка, которую ей передали, и рамки она проверяет
# по ней. Подмена уровня здесь и есть проверяемый ввод; на устройство этот
# challenge не возвращается.
#
# Третий — эфемерная точка, которой перебивается полученная. Нужен кейсу про
# код, посчитанный из одного статического ключа устройства (см. run_conversation,
# источник device-key).
#
# Четвёртый — личный номер инженера, которым перебивается полученный. Нужен кейсу
# про код под чужим именем: устройство ждёт код на номер, который ему назвали на
# промпте, а выдаче называют другой.
wire_with_overrides() {
    local wire="$1" level_override="${2:-}" ephemeral_override="${3:-}" \
        engineer_override="${4:-}"
    case "$wire" in
        "tessera-codes/v1/signed-challenge;"*) ;;
        *) die "challenge не в проводной форме подписанного challenge: $wire" ;;
    esac
    # Перебивка идёт по ключу, а не по позиции: порядок полей задаёт контракт, и
    # хелпер, считающий поля сам, разошёлся бы с ним на первом же изменении.
    [ -z "$level_override" ] || wire="$(replace_field "$wire" level "$level_override")"
    [ -z "$engineer_override" ] || wire="$(replace_field "$wire" engineer "$engineer_override")"
    [ -z "$ephemeral_override" ] || wire="$(replace_field "$wire" ephemeral "$ephemeral_override")"
    printf '%s' "$wire"
}

# Заменяет значение одного поля проводной формы.
# Значение одного поля проводной формы. Читается тем же разбором по ключу, что и
# перебивка: порядок полей задаёт контракт, и хелпер, считающий поля позициями,
# разошёлся бы с ним на первом же изменении.
field_value() {
    local wire="$1" key="$2" value
    value="$(printf '%s' ";$wire" | sed -n "s/.*;$key=\\([^;]*\\).*/\\1/p")"
    [ -n "$value" ] || die "в проводной форме нет поля $key: $wire"
    printf '%s' "$value"
}

replace_field() {
    local wire="$1" key="$2" value="$3"
    case ";$wire" in
        *";$key="*) ;;
        *) die "в проводной форме нет поля $key: $wire" ;;
    esac
    printf '%s' "$wire" | sed "s/;$key=[^;]*/;$key=$value/"
}

# Инструмент стенда, подписывающий challenge ключом устройства.
#
# Зовётся ровно в одном месте: там, где моделируется снятый диск и подменённый
# challenge надо подписать так, как подписал бы атакующий с ключом на руках.
# Своей подписи у хелпера нет и быть не может — канонические байты сообщения
# собирает крейт контракта, а второе их написание на языке оболочки разошлось бы
# с первым молча, и кейс проверял бы сходство двух написаний.
#
# Бинарь доставляет раннер, как и `issuer`: секция `[[artifacts]]` в stand.toml.
# Отсутствие инструмента — сбой стенда, а не отказ продукта, и говорится об этом
# именно так.
SIGN_TOOL="${TESSERA_E2E_XTASK:-tessera-xtask}"

sign_challenge() {
    local signed="$1"
    command -v "$SIGN_TOOL" >/dev/null 2>&1 || die \
        "не найден $SIGN_TOOL — подписать подменённый challenge нечем; бинарь доставляет раннер ([[artifacts]] в stand.toml)"

    # Инструмент подписывает НЕподписанную форму, а у хелпера на руках
    # подписанная: снимается хвост с подписью и возвращается исходный префикс.
    # Порядок и написание полей при этом не повторяются нигде — строку собрал
    # само устройство, здесь у неё только отрезан хвост.
    local unsigned="${signed%;signature=*}"
    unsigned="tessera-codes/v1/challenge${unsigned#tessera-codes/v1/signed-challenge}"

    "$SIGN_TOOL" codes-sign-challenge \
        --challenge "$unsigned" \
        --key "$FIXTURES_CODES_DIR/device-key.pem" \
        || die "$SIGN_TOOL не подписал challenge"
}

# Открытая половина СТАТИЧЕСКОГО ключа устройства — та, что записана в реестре
# устройства (`key=` в device-record.txt). Именно её знает всякий, кто снял с
# устройства диск: приватную половину он берёт из device.p12.
device_static_point() {
    local record="$FIXTURES_CODES_DIR/device-record.txt"
    local point
    point="$(sed -n 's/.*;key=\([0-9a-fA-F]*\);.*/\1/p' "$record")"
    [ -n "$point" ] || die "в $record не нашлось поля key= с открытым ключом устройства"
    printf '%s' "$point"
}

# Единственное место, где хелпер обращается к выдаче. Если интерфейс CLI
# изменится, правится только эта функция — и нигде в хелпере нет ветки, которая
# посчитала бы код сама, когда команда недоступна: молчаливый обход контракта
# хуже красного кейса.
#
# Печатает stdout выдачи, диагностику кладёт в $1, возвращает её код возврата.
run_issue() {
    # `${3-…}`, а НЕ `${3:-…}`: подстановка по двоеточию срабатывает и на
    # пустой аргумент, поэтому кейс «выдача без основания» подавал нормальное
    # основание и не проверял ничего. Пустая строка здесь — законный ввод.
    local err_file="$1" wire="$2" grounds="${3-$DEFAULT_GROUNDS}" request_wire="${4-$2}"
    command -v issuer >/dev/null 2>&1 || die \
        "не найден issuer — код выдаёт только 'issuer codes issue', своей формулы у хелпера нет"

    # Четвёртый аргумент — challenge, ВОКРУГ КОТОРОГО собирается запрос инженера,
    # по умолчанию тот же самый. Он расходится с предъявляемым ровно там, где
    # проверяется отказ на challenge, который вообще не разбирается: собрать
    # запрос вокруг неразбираемого документа нечем, и попытка сделать это упала
    # бы инструментом стенда вместо ответа выдачи.
    local request="$RUN_DIR/request.txt"
    build_request "$request_wire" "$grounds" > "$request"

    # Ключ согласования берётся из копии с правами 0600 (см. stage_server_key):
    # владельческий гейт CLI отвергает файл, доступный кому-то ещё, а фикстуры
    # приезжают с правами репозитория.
    #
    # Признак «личность не подтверждена» флагом не задаётся и не может: он
    # выводится из САМОГО ЗАПРОСА — подписан он аутентификатором инженера или
    # несёт явный вариант «не подтверждено» (`EngineerSignature`). Флаг рядом с
    # документом был бы вторым ответом на вопрос, на который документ уже
    # отвечает, и они разошлись бы.
    issuer codes issue \
        --challenge "$wire" \
        --request "$request" \
        --device-record "$FIXTURES_CODES_DIR/device-record.txt" \
        --ticket "$FIXTURES_CODES_DIR/operator-ticket.txt" \
        --anchor-ticket-authority "$FIXTURES_CODES_DIR/ticket-authority.pem" \
        --anchor-organisation "$ORGANISATION_ID=$FIXTURES_CODES_DIR/organisation-anchor.pem" \
        --anchor-organisation "$OWNER_ID=$FIXTURES_CODES_DIR/owner-anchor.pem" \
        --soft-key "$SERVER_KEY" \
        --code-only 2> "$err_file"
}

# Собирает подписанный запрос инженера вокруг снятого challenge.
#
# Основание живёт ВНУТРИ запроса и второго экземпляра не имеет: у выдачи нет
# флага «причина», и подать её мимо подписанного документа нечем. Пустое
# основание — законный ввод этой функции: на нём стоит кейс CODE-020, и
# отвергнуть его обязана выдача, а не хелпер.
#
# Собирает документ инструмент стенда, и БЕЗ КЛЮЧА: аутентификатора инженера на
# стенде нет, поэтому запрос несёт явный вариант «никто не подписывал» с
# причиной. Подписать чужим ключом было бы хуже пропуска — запись выдачи тогда
# читалась бы как выдача человеку, которого кто-то проверил. Как только у
# инженера появится настоящий ключ, он приедет в комплект фикстур и здесь
# добавится `--key`.
build_request() {
    local wire="$1" grounds="$2"
    command -v "$SIGN_TOOL" >/dev/null 2>&1 || die \
        "не найден $SIGN_TOOL — собрать подписанный запрос инженера нечем; бинарь доставляет раннер ([[artifacts]] в stand.toml)"

    "$SIGN_TOOL" codes-sign-request \
        --challenge "$wire" \
        --grounds "$grounds" \
        || die "$SIGN_TOOL не собрал запрос инженера"
}

# Выдача для входа: код или смерть. Отказ выдачи здесь — сбой стенда: кейсы
# входа предъявляют устройству код, и не получить его значит не дойти до
# проверяемой гарантии.
issue_code() {
    local wire="$1"
    local err="$RUN_DIR/issue.err"
    local out rc=0
    out="$(run_issue "$err" "$wire")" || rc=$?
    if [ "$rc" -ne 0 ]; then
        cat "$err" >&2
        # Класс отказа называется прямо в диагностике: без него разбор упавшего
        # кейса начинается с чтения локализованного текста, а он говорит человеку
        # у страницы инженера, а не тому, кто разбирает прогон.
        die "issuer codes issue вернул $rc ($(issue_outcome "$rc")/$(issue_refusal_class "$err")) для challenge: $wire"
    fi
    # `--code-only` печатает ровно одну строку — сам код. Разбирать тут нечего, и
    # разбор был бы вреден: догадка о формате вывода — тот же обход контракта,
    # что и своя формула, только по другому месту.
    printf '%s' "$out"
}

# Параметры парка (длина кода, ширины счётчика и хвоста, алфавит, профиль) не
# передаются: стенд идёт на умолчаниях контракта, и они же стоят в `[codes]`.
# Как только кейсу понадобится нестандартный парк, значения обязаны приехать
# сюда и в конфигурацию из ОДНОГО источника — разошедшиеся половины дают
# «код не подходит» без объяснения.

# ----------------------------------------------------------------------------
# Разговор PAM
# ----------------------------------------------------------------------------

# Уровень МКЦ приходит из метки процесса, а не из аргумента: его читает сам
# модуль. Значит, прогон на запрошенный уровень — это прогон процесса с такой
# меткой, и подменить её изнутри хелпера нечем. Если стенд умеет запускать
# команду на заданном уровне, он говорит об этом шаблоном в TESSERA_E2E_LEVEL_EXEC
# ({level} подставляется). Не умеет и уровень не совпадает с текущим — это отказ
# стенда, а не продукта: молча прогнать на уровне 0 кейс про уровень 2 значит
# получить зелёный, ничего не проверивший.
current_level() {
    local label
    if [ -r /proc/self/attr/current ]; then
        label="$(tr -d '\0' < /proc/self/attr/current)"
    fi
    if [ -n "${label:-}" ]; then
        printf '%s' "$label" | cut -d: -f2
    else
        # Метки нет — системы без мандатного механизма работают на уровне 0
        # по построению (см. codes_level).
        printf '0'
    fi
}

level_prefix() {
    local level="$1" now
    now="$(current_level)"
    if [ "$level" = "$now" ]; then
        return 0
    fi
    if [ -n "${TESSERA_E2E_LEVEL_EXEC:-}" ]; then
        printf '%s' "${TESSERA_E2E_LEVEL_EXEC//\{level\}/$level}"
        return 0
    fi
    die "процесс идёт на уровне $now, а кейсу нужен $level; стенд не умеет ставить уровень (нет TESSERA_E2E_LEVEL_EXEC) — нужен профиль с mac"
}

# Ведёт один разговор целиком и возвращает его код.
#
# Ответы подаются в FIFO по мере промптов: код третьего ответа существует только
# после того, как модуль напечатал challenge, а challenge появляется на stderr
# драйвера уже после первого ответа. Один поток stdin здесь не годится — драйвер
# для того и умеет `--answers-per-prompt`.
#
# $1 — учётная запись, $2 — уровень, $3 — как получить коды: `issue` (спросить
# оператора), `device-key` (посчитать по прежней схеме, из статического ключа
# устройства), `other-name` (посчитать на чужой личный номер), `wrong`
# (заведомо неверный), либо `fixed:<код>`; $4 — сколько раз отвечать на промпт
# кода.
#
# Разговор графического входа отличается от текстового не кодом, а КАНАЛОМ, и
# отличия задаются двумя массивами, которые команда выставляет перед вызовом:
# DRIVER_FLAGS — чем запускается драйвер (нет имени учётной записи, items с
# дисплеем), LEADING_ANSWERS — ответы, которые греетер отдаёт ДО ответа про
# сервер выдачи (имя из формы, пустое поле пароля).
run_conversation() {
    local user="$1" level="$2" source="$3" code_answers="$4"
    local prefix
    prefix="$(level_prefix "$level")"

    install -d -m 0700 "$RUN_DIR"
    local fifo="$RUN_DIR/conv.in"
    local out="$RUN_DIR/conv.out"
    local err="$RUN_DIR/conv.err"
    rm -f "$fifo" "$out" "$err"
    mkfifo -m 0600 "$fifo"

    # Окружение дисплея снимается ровно тогда, когда разговор идёт каналом
    # греетера: у процесса fly-dm этих переменных нет, и разговор, который
    # унаследовал бы их от прогона кейса, проверял бы запасной путь вместо
    # проверяемого.
    local -a scrub=()
    if [ "$GREETER_CHANNEL" = "1" ]; then
        scrub=(env -u DISPLAY -u XAUTHORITY)
    fi
    # Имя, которым открывается транзакция. У греетера оно не то, под которым
    # идёт вход: он открывает транзакцию пустым именем и называет учётную
    # запись ответом на промпт.
    local driver_user="${DRIVER_USER-$user}"

    # shellcheck disable=SC2086  # prefix — команда с аргументами, разбиение намеренно
    "${scrub[@]}" $prefix pam-drive "${DRIVER_FLAGS[@]}" --answers-per-prompt \
        "$PAM_SERVICE_NAME" "$driver_user" authenticate \
        < "$fifo" > "$out" 2> "$err" &
    local driver=$!
    DRIVER_PID="$driver"

    # FIFO открывается на запись после запуска читателя и держится открытым до
    # конца разговора: закрытый дескриптор — это EOF, а EOF на промпте драйвер
    # считает ошибкой разговора.
    exec 3> "$fifo"
    local leading
    for leading in "${LEADING_ANSWERS[@]}"; do
        printf '%s\n' "$leading" >&3
    done
    printf '%s\n' "$SERVER_ID" >&3
    printf '%s\n' "$ENGINEER_ID" >&3
    printf '%s\n' "$DEVICE_KEY_PIN" >&3

    local code=""
    case "$source" in
        issue)
            local printed
            if printed="$(await_challenge "$err" "$driver")"; then
                code="$(issue_code "$(wire_with_overrides "$printed")")"
                [ -n "$code" ] || die "выдача не вернула код (см. $err)"
                printf '%s\n' "$code" > "$RUN_DIR/last-code"
            fi
            ;;
        device-key)
            # Код по ПРЕЖНЕЙ схеме: из статического ключа устройства, без
            # эфемерной пары попытки. Именно его считает тот, у кого на руках
            # содержимое диска и билет, — и больше ничего.
            #
            # Своей формулы у хелпера по-прежнему нет: считает всё та же
            # `issuer codes issue`, ей лишь подменяется эфемерная точка на
            # открытую половину статического ключа устройства. Обмен ключами
            # симметричен, поэтому выдача своим ключом против статической точки
            # приходит ровно к тому `Z`, к которому атакующий приходит
            # статическим ключом устройства против ключа билета.
            #
            # Подменённая строка ПОДПИСЫВАЕТСЯ ЗАНОВО ключом устройства, и это
            # не поблажка стенду: у моделируемого атакующего ключ есть по
            # условию задачи — он снял диск. Кейс, где отказ приходил бы по
            # подписи, проверял бы не ту гарантию: настоящий атакующий этого
            # класса подписал бы законно. Отказ обязан прийти из сверки кода.
            #
            # Подписывает инструмент стенда — теми же байтами, что и продукт,
            # через тот же крейт контракта (см. sign_challenge).
            local printed
            if printed="$(await_challenge "$err" "$driver")"; then
                code="$(issue_code "$(sign_challenge \
                    "$(wire_with_overrides "$printed" "" "$(device_static_point)")")")"
                [ -n "$code" ] || die "выдача не вернула код (см. $err)"
                printf '%s\n' "$code" > "$RUN_DIR/last-code"
            fi
            ;;
        other-name)
            die "режим other-name недоступен: подмена личного номера ломает подпись устройства, и проверяется теперь отказом выдачи — см. expect-issue-refused-under-another-name"
            ;;
        wrong) code="$WRONG_CODE" ;;
        mistyped-then-right)
            # Инженер ошибся в коде и со второго раза ввёл верный — самая
            # обычная вещь, ради которой у nonce и есть бюджет попыток.
            # Устройство пишет в свою цепочку ДВЕ строки на один nonce: отказ и
            # успех. Кейс сверки живёт именно на этом журнале.
            local printed
            if printed="$(await_challenge "$err" "$driver")"; then
                code="$(issue_code "$(wire_with_overrides "$printed")")"
                [ -n "$code" ] || die "выдача не вернула код (см. $err)"
                printf '%s\n' "$code" > "$RUN_DIR/last-code"
                printf '%s\n' "$WRONG_CODE" >&3
                # Первый ответ уже подан; остальные — верный код.
                code_answers=$((code_answers - 1))
            fi
            ;;
        fixed:*) code="${source#fixed:}" ;;
        *) die "неизвестный источник кода: $source" ;;
    esac

    # Кода может не быть вовсе: разговор кончился раньше, чем его спросили.
    # Писать в FIFO, которого никто не читает, — верный способ получить сбой
    # хелпера поверх уже состоявшегося вердикта.
    local i
    if [ -n "$code" ]; then
        for ((i = 0; i < code_answers; i++)); do
            printf '%s\n' "$code" >&3
        done
    fi
    exec 3>&-

    local rc=0
    wait "$driver" || rc=$?
    DRIVER_PID=""
    rm -f "$fifo"

    # Вывод драйвера прокидывается как есть: кейс пишет ожидания по его строкам,
    # и переписанный здесь вердикт означал бы, что кейс проверяет хелпер.
    cat "$out"
    cat "$err" >&2
    return "$rc"
}

# Ведёт разговор только до напечатанного challenge и обрывает его. Нужен там,
# где проверяется сторона выдачи: устройство обязано выдать настоящий
# challenge (со своим счётчиком и nonce), а вердикт входа к делу не относится.
# Обрыв — закрытый stdin: драйвер сообщит об оборванном разговоре, и это
# ожидаемо, поэтому его код возврата здесь не читается.
#
# Результат кладётся в файл, а не в stdout: функция зовётся не подстановкой,
# чтобы фоновый драйвер оставался виден обработчику выхода (см. stop_driver).
capture_challenge() {
    local user="$1"
    install -d -m 0700 "$RUN_DIR"
    local fifo="$RUN_DIR/conv.in"
    local out="$RUN_DIR/conv.out"
    local err="$RUN_DIR/conv.err"
    rm -f "$fifo" "$out" "$err"
    mkfifo -m 0600 "$fifo"

    local -a scrub=()
    if [ "$GREETER_CHANNEL" = "1" ]; then
        scrub=(env -u DISPLAY -u XAUTHORITY)
    fi
    "${scrub[@]}" pam-drive "${DRIVER_FLAGS[@]}" --answers-per-prompt \
        "$PAM_SERVICE_NAME" "${DRIVER_USER-$user}" authenticate \
        < "$fifo" > "$out" 2> "$err" &
    DRIVER_PID=$!

    exec 3> "$fifo"
    local leading
    for leading in "${LEADING_ANSWERS[@]}"; do
        printf '%s\n' "$leading" >&3
    done
    printf '%s\n' "$SERVER_ID" >&3
    printf '%s\n' "$ENGINEER_ID" >&3
    printf '%s\n' "$DEVICE_KEY_PIN" >&3

    local printed=""
    printed="$(await_challenge "$err" "$DRIVER_PID")" \
        || die "разговор кончился раньше challenge, а команде нужен именно он (см. $err)"
    exec 3>&-
    wait "$DRIVER_PID" 2>/dev/null || true
    DRIVER_PID=""
    rm -f "$fifo"

    printf '%s\n' "$printed" > "$CHALLENGE_FILE"
}

# Ведёт разговор до ПРОМПТА КОДА и обрывает его.
#
# Отличие от capture_challenge — в том, чего именно ждать. Там ждут строку
# challenge, и её отсутствие законно считается сбоем стенда: команде, которой
# challenge нужен для выдачи, без него делать нечего. Здесь проверяется САМ
# ПОКАЗ, и «промпт кода пришёл без challenge» — это ответ продукта, а не
# поломка: ждать надо вопрос, а не показ.
capture_code_prompt() {
    local user="$1"
    install -d -m 0700 "$RUN_DIR"
    local fifo="$RUN_DIR/conv.in"
    local out="$RUN_DIR/conv.out"
    local err="$RUN_DIR/conv.err"
    rm -f "$fifo" "$out" "$err"
    mkfifo -m 0600 "$fifo"

    local -a scrub=()
    if [ "$GREETER_CHANNEL" = "1" ]; then
        scrub=(env -u DISPLAY -u XAUTHORITY)
    fi
    "${scrub[@]}" pam-drive "${DRIVER_FLAGS[@]}" --answers-per-prompt \
        "$PAM_SERVICE_NAME" "${DRIVER_USER-$user}" authenticate \
        < "$fifo" > "$out" 2> "$err" &
    DRIVER_PID=$!

    exec 3> "$fifo"
    local leading
    for leading in "${LEADING_ANSWERS[@]}"; do
        printf '%s\n' "$leading" >&3
    done
    printf '%s\n' "$SERVER_ID" >&3
    printf '%s\n' "$ENGINEER_ID" >&3

    await_code_prompt "$err" "$DRIVER_PID"
    exec 3>&-
    wait "$DRIVER_PID" 2>/dev/null || true
    DRIVER_PID=""
    rm -f "$fifo"
}

# Ждёт, пока драйвер напечатает промпт кода — с символом или без него.
#
# Опознаётся по любой из трёх шапок: подпись над рисунком QR, подпись над
# текстовой формой адреса, сам вопрос. Первый промпт кода несёт показ и вопрос
# одним обменом, и что из трёх пришло — предмет проверки, а не условие ожидания;
# ждать одну конкретную форму значило бы считать сбоем стенда любую другую.
await_code_prompt() {
    local err="$1" driver="$2" waited=0
    local limit="${TESSERA_E2E_CHALLENGE_TIMEOUT:-30}"
    while :; do
        if grep -qE "^prompt: ($QR_CAPTION_LINE|$QR_FALLBACK_LINE|${CODE_PROMPT_LINE% })" "$err" 2>/dev/null; then
            return 0
        fi
        # Разговор кончился раньше вопроса — вердикт уже вынесен, и ждать
        # больше нечего. Проверку делает вызывающий по тому, что в журнале.
        kill -0 "$driver" 2>/dev/null || return 0
        sleep 0.2
        waited=$((waited + 1))
        [ "$waited" -lt $((limit * 5)) ] || die "промпт кода не появился за ${limit} с (см. $err)"
    done
}

# Ждёт показанный challenge на stderr драйвера. Строка приходит в тексте промпта
# кода — не через PAM_TEXT_INFO: на fly-dm он до экрана не доходит вовсе, — и
# несёт проводную форму подписанного challenge целиком. Ожидание ограничено:
# разговор, застрявший до промпта кода, обязан кончиться диагностикой, а не
# висеть до таймаута кейса.
await_challenge() {
    local err="$1" driver="$2" waited=0
    local limit="${TESSERA_E2E_CHALLENGE_TIMEOUT:-30}"
    while :; do
        local line
        line="$(grep -m1 -o -E 'tessera-codes/v1/signed-challenge;[^[:space:]]+' "$err" 2>/dev/null || true)"
        if [ -n "$line" ]; then
            printf '%s' "$line"
            return 0
        fi
        # Разговор кончился раньше challenge — это ВЕРДИКТ, а не сбой стенда:
        # устройство отказывает до показа challenge по доброму десятку причин
        # (имя не ролевой учётной записи, пустой ответ, исчерпанный бюджет
        # выдачи). Код возврата драйвера отдаётся кейсу как есть; хелпер,
        # умиравший здесь служебным кодом, превращал отказ продукта в ERROR, и
        # настоящий дефект читался как испорченный стенд.
        if ! kill -0 "$driver" 2>/dev/null; then
            return 1
        fi
        sleep 0.2
        waited=$((waited + 1))
        # А вот это сбой стенда: разговор жив и молчит. Ждать до таймаута кейса
        # значит потерять и разбор, и следующие кейсы.
        [ "$waited" -lt $((limit * 5)) ] || die "challenge не появился за ${limit} с (см. $err)"
    done
}

