# Идемпотентен и не опирается на prepare: teardown кейса выполняется при любом
# исходе, включая падение подготовки на середине.
cmd_cleanup() {
    [ "$(id -u)" = "0" ] || die "требуются права root"

    if [ -f "$CONFIG_BACKUP" ]; then
        local staging="$CONFIG.e2e-codes"
        cp "$CONFIG_BACKUP" "$staging"
        if [ -f "$CONFIG" ]; then
            chmod --reference="$CONFIG" "$staging"
            chown --reference="$CONFIG" "$staging"
        fi
        mv -f "$staging" "$CONFIG"
        rm -f "$CONFIG_BACKUP"
    fi

    rm -f "$PAM_SERVICE"

    # Стек sshd возвращается, даже если ssh-ветвь оборвалась на середине: на
    # неодноразовой машине оставленный стек закрыл бы вход всем остальным.
    if [ -f "$SSH_PAM_BACKUP" ]; then
        cp "$SSH_PAM_BACKUP" "$SSH_PAM_SERVICE"
        chmod 0644 "$SSH_PAM_SERVICE"
        rm -f "$SSH_PAM_BACKUP"
    fi
    if [ -f "$SSHD_DROPIN" ]; then
        rm -f "$SSHD_DROPIN"
        reload_sshd || true
    fi

    # Убирается только то, что разложил prepare, а сам каталог — лишь если после
    # этого он пуст: устройство парка могло получить артефакты не от прогона.
    rm -f "$CODES_DIR/device.p12" "$CODES_DIR/tickets.txt" \
        "$CODES_DIR/tickets.revoked" "$CODES_DIR/ticket-authority.pem" \
        "$CODES_DIR/page-urls.txt"
    rm -rf "$STATE_DIR"
    rmdir "$CODES_DIR" 2>/dev/null || true

    rm -rf "$RUN_DIR"
    # Удаляется ТОЛЬКО то, что стенд сам сюда положил, и только если после
    # этого каталог пуст: путь приходит из окружения, а `rm -rf` по чужому
    # каталогу — не уборка, а потеря. Проверка та же, что у ролевого
    # хранилища.
    if [ -n "${WRAPPER_DIR:-}" ]; then
        assert_removable_path "$WRAPPER_DIR" "WRAPPER_DIR"
        rm -f "$WRAPPER_DIR/overlay-acks"
        rmdir "$WRAPPER_DIR" 2>/dev/null || true
    fi

    echo "cleaned"
}

