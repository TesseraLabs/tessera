#!/usr/bin/env bash
# codes-server.sh — серверный канал входа по коду со стороны стенда.
#
# Хелпер исполняет две роли, которые на объекте исполняют человек и сервер: он
# раскладывает на устройстве артефакты Codes, ведёт разговор PAM за инженера и,
# сняв показанный challenge, собирает подписанный запрос инженера и несёт его
# выдаче. Выдача здесь — консольная команда `issuer codes issue`, то самое
# открытое ядро, которое codes-core вызывает внутри себя, и код считает ТОЛЬКО
# она: вторая реализация формулы в шелле разошлась бы с продуктом молча, а
# проявилось бы расхождение не в CI, а как «код не подходит» у инженера на
# объекте. Ради исключения этого заведён контрактный крейт, и хелпер этой
# границы не переходит.
#
#   codes-server.sh prepare <fixtures>/codes [--without-codes-url] [--with-overlay]
#   codes-server.sh authenticate <user> --level N
#   codes-server.sh authenticate-with-code <user> --level N --code <код>
#   codes-server.sh authenticate-with-device-key <user> --level N
#   codes-server.sh expect-issue-refused-under-another-name <user> --level N
#   codes-server.sh expect-issue-refused <user> --level N
#   codes-server.sh expect-issue-refused-without-grounds <user> --level N
#   codes-server.sh expect-transposed-number-refused <user>
#   codes-server.sh expect-personal-number-refused <user>
#   codes-server.sh expect-custody-tier-in-record
#   codes-server.sh expect-unverified-identity-in-record
#   codes-server.sh issue-without-login <user> --level N
#   codes-server.sh exhaust-attempts <user>
#   codes-server.sh replay-in-new-conversation <user>
#   codes-server.sh replay-after-restart <user>
#   codes-server.sh authenticate-without-code <user>
#   codes-server.sh expect-qr-decodes-to-challenge <user>
#   codes-server.sh expect-qr-in-code-prompt <user>
#   codes-server.sh expect-prompt-order <user>
#   codes-server.sh set-page-url <url>
#   codes-server.sh issue-code-for-wire <challenge>
#   codes-server.sh authenticate-over-ssh <user> --level N
#   codes-server.sh revoke-ticket
#   codes-server.sh cleanup
#
# Разговор состоит из четырёх ответов подряд («Сервер: », «Личный номер: », PIN
# контейнера, «Код: »), и последний вычисляется по тому, что модуль показал перед
# промптом кода. Поэтому ответы не подаются одним куском: драйвер запускается с
# `--answers-per-prompt`, его stdin — FIFO, и код кладётся туда уже после того,
# как challenge снят со stderr.
#
# Все команды идемпотентны, `cleanup` выполняется и там, где `prepare` не
# отработал: teardown кейса зовёт его при любом исходе.
#
# Каталог фикстур описывает сам себя файлом `device.env` — см. «Ожидаемые
# фикстуры» ниже. Без него хелперу пришлось бы угадывать номер устройства, эпоху
# и рамки, а несовпадение любого из них с материалом ключей выглядело бы как
# отказ продукта.
#
# Имена файлов фикстур (`operator-key.pem`, `operator-ticket.txt`) остались от
# телефонной редакции: их выпускает генератор фикстур, и переименование комплекта
# идёт отдельно от этой волны. Роль файлов теперь серверная — ключ согласования
# сервера и билет сервера.

set -euo pipefail

PATH="/sbin:/usr/sbin:$PATH"
export PATH

# Служебные коды: 64 — ошибка вызова, 70 — сбой стенда. Профили перечисляют их в
# error_exit_codes, поэтому кейс отличит сломанный стенд от отказа продукта.
EXIT_USAGE=64
EXIT_INTERNAL=70

CONFIG="${TESSERA_E2E_CONFIG:-/etc/tessera/config.toml}"
# Эталон конфигурации снимается один раз, при первой правке, и живёт вне /run:
# cleanup обязан вернуть файл и после перезапуска окружения.
CONFIG_BACKUP=/var/lib/tessera/e2e-codes-config.orig
PAM_SERVICE="${TESSERA_E2E_CODES_PAM_SERVICE:-/etc/pam.d/codeauth}"
PAM_SERVICE_NAME="$(basename "$PAM_SERVICE")"

# Стек sshd и конфигурация ssh — их правит только ветвь authenticate-over-ssh, и
# только она: остальные кейсы системных стеков не трогают. Резерв лежит вне /run,
# чтобы cleanup вернул прежний стек и после перезапуска окружения.
SSH_PAM_SERVICE="${TESSERA_E2E_SSHD_PAM:-/etc/pam.d/sshd}"
SSH_PAM_BACKUP=/var/lib/tessera/e2e-codes-sshd-pam.orig
SSHD_DROPIN="${TESSERA_E2E_SSHD_DROPIN:-/etc/ssh/sshd_config.d/99-tessera-e2e-codes.conf}"
SSH_HOST="${TESSERA_E2E_SSH_HOST:-127.0.0.1}"
SSH_PORT="${TESSERA_E2E_SSH_PORT:-22}"

# Каталог артефактов устройства. Пишется в `[codes].dir` явно: дефолт продукта и
# дефолт хелпера обязаны быть одним значением, а не двумя совпадающими.
CODES_DIR="${TESSERA_E2E_CODES_DIR:-/var/lib/tessera/codes}"
STATE_DIR="$CODES_DIR/state"

# Состояние прогона — в /run: перезапуск окружения обнуляет его сам.
RUN_DIR="${TESSERA_E2E_STATE_DIR:-/run/tessera-e2e}/codes"
PREPARED="$RUN_DIR/prepared.env"
# Цепочка выдач: на каждую выдачу — подписанный запрос инженера, грант, ступень
# кастодии ключа согласования и признак «личность не подтверждена».
#
# Её пишет тот, кто считает и ПОДПИСЫВАЕТ грант, — служба выдачи. `issuer codes
# issue` подписи не ставит: ключа подписи у него нет по построению, и второго
# места, где эта цепочка бы рождалась, заводить нельзя. Пока службы нет, файла
# нет тоже, и команды, читающие запись, говорят об этом прямо, а не выдумывают
# ступень.
#
# Цепочка и состояние устройства обнуляются ОДНОВРЕМЕННО, подкомандой prepare:
# сверка (`issuer codes reconcile`, сюита 31) сопоставляет выдачи с журналом
# устройства, и половина от прошлого прогона рядом со свежей половиной даёт
# находки, которых на приборе не было.
SERVER_CHAIN="$RUN_DIR/server-chain.ndjson"
# Рабочая копия приватного ключа согласования сервера: CLI требует от файла ключа
# прав 0600, а фикстуры приезжают с правами репозитория и правятся раннером до
# root:root, но не до 0600.
SERVER_KEY="$RUN_DIR/operator-key.pem"
# Снятый с устройства challenge — им работают команды, проверяющие сторону
# выдачи.
CHALLENGE_FILE="$RUN_DIR/challenge.txt"

# Бюджет попыток ввода кода. Пишется в конфигурацию устройства явно (см.
# deploy_config): хелпер обязан подать РОВНО столько неверных кодов, сколько
# позволяет модуль, и единственный способ не разойтись — не полагаться на
# умолчание контракта с обеих сторон, а задать число в одном месте.
ATTEMPTS_PER_NONCE="${TESSERA_E2E_CODE_ATTEMPTS:-5}"

# Фиктивная куки дисплея: шестнадцать нулевых байтов. Секретом не является и
# доступа ни к какому дисплею не даёт — она нужна там, где проверяется КАНАЛ
# передачи, а не сам доступ.
DUMMY_COOKIE_HEX="00000000000000000000000000000000"

# Промпт имени учётной записи, как его печатает модуль. Держится здесь ровно
# затем, чтобы проверять ЧИСЛО таких промптов: второй означает переспрос.
NAME_PROMPT_LINE="${TESSERA_E2E_NAME_PROMPT:-Имя учётной записи: }"

# Промпт личного номера инженера: по его наличию видно, что идентификатор
# сервера выдачи модуль уже принял.
ENGINEER_PROMPT_LINE="${TESSERA_E2E_ENGINEER_PROMPT:-Личный номер: }"

# Журнал аудита устройства со сцеплением хешей — вторая половина проверки следа.
AUDIT_JOURNAL="${TESSERA_E2E_AUDIT_JOURNAL:-/var/lib/tessera/audit.ndjson}"

# Заведомо неверный код: восемь нулей — длина по умолчанию, десятичный алфавит,
# не сходится ни с каким общим ключом. Секретом не является.
WRONG_CODE="00000000"

# Основание выдачи. Живёт внутри подписанного запроса инженера; на объекте это
# наряд или заявка, здесь — имя прогона, чтобы запись выдачи говорила, откуда она.
DEFAULT_GROUNDS="${TESSERA_E2E_CODES_GROUNDS:-e2e codes-server}"

# Личный номер инженера, которым хелпер представляется на промпте «Личный номер: ».
# Сверять его не с чем: реестра людей на офлайн-устройстве нет, — но в байты кода
# он входит, поэтому значение обязано быть ОДНО на обе стороны: устройство берёт
# его из ответа на промпт, выдача — из challenge, куда его положило устройство.
# В device.env не вынесен намеренно: фикстуры о нём ничего не знают и знать не
# должны, иначе комплект пришлось бы пересобирать ради строки.
#
# Номер по правилу ENG-010: сегмент организации, серийная часть, контрольный
# символ ISO 7064 MOD 37,36. Раньше здесь стояло `eng-1` — устройство отвергает
# такое значение на промпте, ДО порождения challenge, и каждый кейс CODE уткнулся
# бы в отказ по чужой причине. Тот же номер несёт комплект фикстур стенда.
ENGINEER_ID="${TESSERA_E2E_ENGINEER_ID:-ORG1-0000014}"

# Личный номер ДРУГОГО инженера — того, кому код не выдавался. Используется
# только режимом authenticate-under-another-name.
#
# Тоже по правилу, и по той же причине: кейс проверяет, что код не сходится на
# чужой номер, а не то, что негодный номер отвергается формой.
OTHER_ENGINEER_ID="${TESSERA_E2E_OTHER_ENGINEER_ID:-ORG1-0000022}"

# Чем запускается драйвер, каким именем открывается транзакция и что отвечается
# до промпта сервера выдачи. Для текстового входа — пусто и имя как есть: он и
# есть базовый путь. Команды графического входа наполняют это перед разговором
# (см. greeter_modern_channel).
DRIVER_FLAGS=()
LEADING_ANSWERS=()
GREETER_CHANNEL=0
# DRIVER_USER намеренно НЕ задан: «имени нет» и «имя пустое» — разные состояния
# транзакции, и пустая строка здесь открывала бы КАЖДЫЙ разговор так, как это
# делает греетер. Текстовый вход тогда шёл бы чужим каналом, а кейсы, ничего не
# знающие про греетер, получали бы лишний промпт имени. Значение появляется
# только в greeter_modern_channel.

# Пакет первичной настройки, которым на устройство кладётся ключевой материал,
# и файл PIN контейнера доставки. Оба живут только на время `prepare`.
ENROLL_DIR="$RUN_DIR/enroll-package"
PIN_FILE="$RUN_DIR/container.pin"

# Что импорт перезаписывает помимо части Codes. Снимается до импорта и
# возвращается сразу после: этому хелперу от импорта нужен ТОЛЬКО ключевой
# материал метода, а ролевое хранилище кладёт подготовка suite — и вход по коду
# ищет роль именно в нём. Импорт, оставленный как есть, заменяет хранилище
# срезом пакета, и следующий кейс получает отказ `role_unknown` там, где
# проверяется совсем другое.
DEVICE_BACKUP="$RUN_DIR/device-backup"
ROLES_DIR="${TESSERA_E2E_ROLES_DIR:-/var/lib/tessera/roles}"
TAGS_FILE="${TESSERA_E2E_TAGS_FILE:-/etc/tessera/device-tags.toml}"
HOST_P12="${TESSERA_E2E_HOST_P12:-/var/lib/tessera/host.p12}"

# Оверлей графического входа: чьей учётной записью он бежит и откуда берётся.
# Учётная запись — та же, под которой работает греетер; на Astra это `fly-dm`.
# Секция конфигурации пишется только по `prepare --with-overlay`.
WITH_OVERLAY=0
# Заглушке оверлея нужен ключ, чтобы отвечать байтом подтверждения. Бинарь в
# конфигурации — путь без аргументов, поэтому ключ дописывается обёрткой (см.
# write_overlay_wrapper): так кейс остаётся одной строкой, а модуль по-прежнему
# запускает один исполняемый файл.
OVERLAY_ACKS=0
# Где живут исполняемые файлы, которые заводит стенд. Каталог обязан быть на
# файловой системе БЕЗ noexec — рабочий каталог прогона под /run не годится.
WRAPPER_DIR="${TESSERA_E2E_BIN_DIR:-/usr/local/lib/tessera-e2e}"
OVERLAY_USER="${TESSERA_E2E_OVERLAY_USER:-}"
OVERLAY_BINARY="${TESSERA_E2E_OVERLAY_BINARY:-/usr/bin/tessera-qr-overlay}"

# Учётные записи, под которыми может бежать оверлей, в порядке предпочтения.
# Первая — та, под которой работает греетер Astra; вторая — непривилегированная
# учётная запись, которая есть в любом окружении. Выбор по НАЛИЧИЮ, а не по
# имени: модуль отказывается от оверлея, если названной учётной записи на
# устройстве нет, и кейс тогда «проходит» на устройстве без оверлея вовсе.
OVERLAY_USER_CANDIDATES="fly-dm nobody"

die() {
    echo "codes-server: $*" >&2
    exit "$EXIT_INTERNAL"
}

# Драйвер разговора живёт в фоне, и оборванный на середине хелпер оставил бы его
# висеть на FIFO до таймаута кейса. Убирается он одним обработчиком на выход:
# подстановки команд ($(...)) собственный EXIT не исполняют, поэтому живой
# разговор от них не пострадает.
DRIVER_PID=""
stop_driver() {
    [ -n "$DRIVER_PID" ] || return 0
    kill "$DRIVER_PID" 2>/dev/null || true
    DRIVER_PID=""
}

# Выход из хелпера любым путём: оборванный разговор добивается, а снятое перед
# продуктовым импортом возвращается на место.
#
# Второе — не гигиена. Импорт заменяет ролевое хранилище, теги и удостоверение
# узла срезом пакета; хелпер, упавший между снимком и возвратом, оставил бы
# устройство с ЧУЖОЙ ролевой базой, и следующий кейс проверял бы не то
# устройство, не зная об этом. Возврат идемпотентен: без снимка он ничего не
# делает.
on_exit() {
    stop_driver
    restore_device_state_if_taken
}
trap on_exit EXIT

usage_error() {
    echo "codes-server: $*" >&2
    usage
    exit "$EXIT_USAGE"
}

usage() {
    cat >&2 <<'EOF'
usage: codes-server.sh <command> [args]
  prepare <fixtures>/codes [--without-codes-url] [--with-overlay]
                          [--overlay-binary=<путь>] [--overlay-acks]
                        разложить артефакты Codes, включить [codes] и завести
                        PAM-сервис codeauth; --with-overlay дописывает учётную
                        запись и бинарь оверлея графического входа,
                        --overlay-acks запускает его так, что он отвечает
                        байтом подтверждения отрисовки
  authenticate <user> --level N
                        полный вход по коду: снять challenge, получить код у
                        `issuer codes issue`, подать его
  authenticate-as-greeter <user> --level N [--start empty|none]
                        тот же вход, но каналом штатного греетера fly-dm с
                        плагином modern: имя из формы первым ответом, пустое
                        поле пароля вторым. --start задаёт, чем открыта
                        транзакция: пустым именем (по умолчанию, так делает
                        живой греетер) или отсутствующим вовсе
  expect-user-item-untouched <имя>
                        вход под именем, которое задало приложение: отказ, и
                        item PAM_USER обязан остаться тем же значением
  expect-server-id-not-logged <user> <строка>
                        канал греетера, где поле пароля попадает на промпт
                        сервера выдачи: отказ обязан прийти до challenge, а
                        <строка> — не появиться ни в промптах, ни в тексте
                        попытки, ни в журналах
  expect-empty-name-refused <user>
                        канал греетера, где поле имени пусто и больше ничего не
                        подаётся: отказ обязан прийти после ОДНОГО вопроса
  expect-payload-line-in-code-prompt <user>
                        при поднятом оверлее промпт кода обязан нести адрес
                        попытки строкой и не нести рисунок QR
  expect-second-answer-not-logged <user> <строка>
                        канал греетера, где поле имени пусто, а в поле пароля
                        стоит <строка>: вход обязан отказать, имя не должно
                        спрашиваться дважды, а <строка> — попасть в журнал
                        модуля или в журнал аудита
  answer-nothing <user> [level]
                        разговор каналом греетера, где на промпт сервера выдачи
                        дважды приходит пустая строка и больше ничего;
                        печатает вердикт драйвера и отдаёт его код
  authenticate-mistyping-once <user> --level N
                        вход, где первый код набран неверно, а второй верно:
                        журнал устройства получает отказ и успех на ОДИН nonce
  authenticate-with-code <user> --level N --code <код>
                        то же, но код задан снаружи и подаётся как есть;
                        выдача не вызывается вовсе
  authenticate-with-device-key <user> --level N
                        код считается по ПРЕЖНЕЙ схеме — из статического ключа
                        устройства, без участия эфемерной пары попытки;
                        подменённый challenge подписывается тем же ключом
                        устройства (у снявшего диск он есть), ожидается отказ
                        сверки на устройстве
  expect-issue-refused-under-another-name <user> --level N
                        выдаче называют ЧУЖОЙ личный номер инженера;
                        0 только на отказ по подписи устройства
  expect-issue-refused <user> --level N
                        проверить, что выдача НЕ считает код на уровень вне
                        рамок билета; 0 только на отказ по рамкам
  expect-issue-refused-without-grounds <user> --level N
                        запрос без основания: 0 только на отказ по основанию,
                        и он обязан прийти раньше вычисления кода
  expect-personal-number-refused <user>
                        назвать личный номер с неверным контрольным символом;
                        0 только если challenge не порождён вовсе
  expect-transposed-number-refused <user>
                        предъявить выдаче challenge, в номере устройства
                        которого переставлены два соседних знака, — по разу на
                        каждую соседнюю пару; 0 только если каждый раз пришёл
                        отказ классом challenge_malformed
  expect-custody-tier-in-record
                        напечатать ступень кастодии ключа согласования из
                        последней записи выдачи
  expect-unverified-identity-in-record
                        напечатать признак «личность не подтверждена» из
                        последней записи выдачи
  issue-without-login <user> --level N
                        выдать код и не предъявлять его устройству
  exhaust-attempts <user>
                        исчерпать бюджет попыток ввода кода в одном прогоне
  replay-in-new-conversation <user>
                        успешный вход, затем тот же код во втором разговоре —
                        без перезапуска
  replay-after-restart <user>
                        успешный вход, перезапуск устройства, тот же код снова
  authenticate-without-code <user>
                        разговор, в котором код не подаётся вовсе: устройство
                        обязано отказать раньше, чем его спросит
  issue-storm <user> --level N --count M [--recover-after S]
                        M разговоров, обрываемых на напечатанном challenge, и
                        ещё один сверх того: устройство обязано отказать в
                        выдаче временно. С --recover-after выждать S секунд и
                        показать, что метод сам вернулся в строй
  expect-qr-decodes-to-challenge <user>
                        прочитать нарисованный QR сторонним декодером и
                        показать, что он несёт подписанный challenge
  expect-qr-in-code-prompt <user>
                        показать, что QR пришёл в тексте промпта кода, а не
                        отдельным PAM_TEXT_INFO
  expect-prompt-order <user>
                        показать порядок промптов: сервер, личный номер, код
  set-page-url <url>    поставить адрес страницы инженера в [codes]
  issue-code-for-wire <challenge>
                        служебная: код для показанного challenge; нужна
                        ssh-ветви, где разговор ведёт pty-драйвер
  authenticate-over-ssh <user> --level N
                        тот же вход, но PAM ведёт sshd: показ обязан дойти до
                        администратора без физического доступа
  revoke-ticket         дописать номер билета сервера в tickets.revoked
  cleanup               вернуть окружение как было (идемпотентно)
EOF
}

