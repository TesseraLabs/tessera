# ----------------------------------------------------------------------------
# Показ challenge: QR, порядок промптов, адрес страницы
#
# Строки, которые здесь ищутся в выводе, — это то, что видит инженер на экране.
# Повторять их приходится: стенд наблюдает продукт снаружи, константы модуля ему
# недоступны, и сверять текст не с чем, кроме самого текста. Расхождение выглядит
# как неувиденный промпт и разбирается по conv.err.
# ----------------------------------------------------------------------------

QR_CAPTION_LINE="Отсканируйте телефоном:"
QR_FALLBACK_LINE="Или введите вручную:"
CODE_PROMPT_LINE="Код: "
SERVER_PROMPT_LINE="Сервер выдачи: "
ENGINEER_PROMPT_LINE="Личный номер: "

# Печатает строки одного сообщения драйвера, начиная с той, где стоит подпись
# над QR. `pam-drive` печатает многострочное сообщение как есть, поэтому границей
# служит следующая его собственная строка (`prompt: `, `module: `, `<фаза>: `).
shown_message_lines() {
    local err="$1"
    awk -v caption="prompt: $QR_CAPTION_LINE" '
        index($0, caption) == 1 { inside = 1; print substr($0, length("prompt: ") + 1); next }
        inside && /^(prompt|module|auth|account|session|open_session|close_session|pam-drive): / { exit }
        inside { print }
    ' "$err"
}

# Собирает из половинных блоков растр PBM и отдаёт его декодеру.
#
# Своего декодера у стенда нет намеренно: гарантия кейса — «камера читает», и
# сверка рисунка с ожидаемым рисунком её не проверяет. `zbarimg` — тот же
# сторонний читатель, что и телефон; отсутствие инструмента — сбой стенда, а не
# отказ продукта, поэтому require_tool.
decode_qr_block() {
    local block="$1" image="$RUN_DIR/qr.pbm"
    require_tool python3
    require_tool zbarimg

    # Модуль рисуется квадратом из нескольких пикселей: декодер работает по
    # растру, и один пиксель на модуль он берёт неустойчиво.
    python3 - "$block" "$image" <<'PY'
import sys

block, image = sys.argv[1], sys.argv[2]
SCALE = 8
UPPER = {"█": (1, 1), "▀": (1, 0), "▄": (0, 1), " ": (0, 0)}

rows = []
with open(block, encoding="utf-8") as handle:
    for line in handle:
        line = line.rstrip("\n")
        if not line:
            continue
        upper, lower = [], []
        for glyph in line:
            if glyph not in UPPER:
                raise SystemExit(f"неизвестный глиф в рисунке QR: {glyph!r}")
            top, bottom = UPPER[glyph]
            upper.append(top)
            lower.append(bottom)
        rows.append(upper)
        rows.append(lower)

if not rows:
    raise SystemExit("рисунок QR пуст")
width = len(rows[0])
if any(len(row) != width for row in rows):
    raise SystemExit("строки рисунка QR разной длины")

with open(image, "w", encoding="ascii") as out:
    out.write(f"P1\n{width * SCALE} {len(rows) * SCALE}\n")
    for row in rows:
        pixels = " ".join(str(value) for value in row for _ in range(SCALE))
        for _ in range(SCALE):
            out.write(pixels + "\n")
PY

    # `--raw` печатает только полезную нагрузку, без имени символики.
    zbarimg --quiet --raw "$image"
}

# Проверяет, что нарисованный QR ЧИТАЕТСЯ декодером и несёт тот самый документ,
# который устройство подписало.
#
# Чтение сверяется дважды, и второй раз важнее первого: декодированная строка
# сравнивается с текстовой формой под рисунком, а затем ИМЕННО ИЗ НЕЁ собирается
# запрос инженера и подаётся выдаче. Выдача проверяет подпись устройства, поэтому
# посчитанный код доказывает, что символ несёт подписанный challenge, а не
# похожие байты.
cmd_expect_qr_decodes_to_challenge() {
    local user="${1:-}"
    [ -n "$user" ] || usage_error "usage: codes-server.sh expect-qr-decodes-to-challenge <user>"

    load_prepared
    capture_challenge "$user"

    local err="$RUN_DIR/conv.err" block="$RUN_DIR/qr.txt"
    local lines
    lines="$(shown_message_lines "$err")"
    [ -n "$lines" ] || die "в разговоре нет сообщения с подписью «$QR_CAPTION_LINE» (см. $err)"

    # Рисунок — строки между двумя подписями; текстовая форма — первая строка
    # после нижней подписи.
    printf '%s\n' "$lines" \
        | awk -v caption="$QR_CAPTION_LINE" -v fallback="$QR_FALLBACK_LINE" '
            $0 == caption { inside = 1; next }
            $0 == fallback { exit }
            inside { print }
        ' > "$block"
    [ -s "$block" ] || die "между подписями нет рисунка QR (см. $err)"

    local shown
    shown="$(printf '%s\n' "$lines" \
        | awk -v fallback="$QR_FALLBACK_LINE" '
            found { print; exit }
            $0 == fallback { found = 1 }
        ')"
    [ -n "$shown" ] || die "под рисунком нет текстовой формы challenge (см. $err)"

    local decoded
    decoded="$(decode_qr_block "$block")" \
        || die "zbarimg не прочитал нарисованный QR (рисунок: $block)"
    decoded="${decoded%$'\n'}"

    if [ "$decoded" != "$shown" ]; then
        echo "codes-server: QR несёт не то, что напечатано текстом" >&2
        echo "  из символа: $decoded" >&2
        echo "  из текста:  $shown" >&2
        return 1
    fi

    # Полезная нагрузка — адрес страницы, `#` и документ; парк без страницы
    # показывает документ один.
    local document="${decoded##*#}"
    case "$document" in
        "tessera-codes/v1/signed-challenge;"*) ;;
        *)
            echo "codes-server: в прочитанном нет подписанного challenge: $decoded" >&2
            return 1
            ;;
    esac

    local code
    code="$(issue_code "$(wire_with_overrides "$document")")"
    [ -n "$code" ] || die "выдача не вернула код для прочитанного документа"

    printf 'qr-decoded: %s\n' "$document"
}

# Проверяет, что QR приходит В ТЕКСТЕ ПРОМПТА кода, а не отдельным сообщением.
#
# Разница видна по выводу драйвера: `prompt: ` — сообщение, на которое приложение
# обязано ответить, `module: ` — PAM_TEXT_INFO, который fly-modern до экрана не
# доносит. Показ, уехавший в PAM_TEXT_INFO, на консоли выглядит исправным.
cmd_expect_qr_in_code_prompt() {
    local user="${1:-}" as_greeter=0
    shift || true
    while [ $# -gt 0 ]; do
        case "$1" in
            --as-greeter) as_greeter=1 ;;
            *) usage_error "неизвестный аргумент expect-qr-in-code-prompt: $1" ;;
        esac
        shift
    done
    [ -n "$user" ] || usage_error "usage: codes-server.sh expect-qr-in-code-prompt <user> [--as-greeter]"

    load_prepared
    [ "$as_greeter" = "0" ] || greeter_modern_channel "$user"
    capture_code_prompt "$user"

    local err="$RUN_DIR/conv.err"
    if grep -qF "module: $QR_CAPTION_LINE" "$err"; then
        echo "codes-server: QR показан через PAM_TEXT_INFO — на fly-modern это невидимый показ" >&2
        return 1
    fi

    local lines
    lines="$(shown_message_lines "$err")"
    if [ -z "$lines" ]; then
        echo "codes-server: QR не пришёл в тексте промпта (см. $err)" >&2
        return 1
    fi

    # Последняя строка сообщения — сам промпт кода: показ и вопрос обязаны быть
    # одним обменом, иначе греетер покажет вопрос без символа.
    local last
    last="$(printf '%s\n' "$lines" | tail -n 1)"
    if [ "$last" != "$CODE_PROMPT_LINE" ] && [ "$last" != "${CODE_PROMPT_LINE% }" ]; then
        echo "codes-server: сообщение с QR не кончается промптом кода: «$last»" >&2
        return 1
    fi

    echo "qr-in-prompt: yes"
}

# Проверяет порядок промптов: сервер выдачи, личный номер, код.
#
# Первым промптом личный номер быть не может: форму первого промпта греетер
# fly-modern заполняет тем, что человек ввёл в поле входа, и спрошенный первым
# номер молча подменяется.
cmd_expect_prompt_order() {
    local user="${1:-}"
    [ -n "$user" ] || usage_error "usage: codes-server.sh expect-prompt-order <user>"

    load_prepared
    capture_challenge "$user"

    local err="$RUN_DIR/conv.err"
    local order server engineer code
    order="$(grep -n '^prompt: ' "$err" | cut -d: -f1)"
    [ -n "$order" ] || die "в разговоре нет ни одного промпта (см. $err)"

    server="$(grep -n -m1 -F "prompt: $SERVER_PROMPT_LINE" "$err" | cut -d: -f1 || true)"
    engineer="$(grep -n -m1 -F "prompt: $ENGINEER_PROMPT_LINE" "$err" | cut -d: -f1 || true)"
    code="$(grep -n -m1 -F "prompt: $QR_CAPTION_LINE" "$err" | cut -d: -f1 || true)"

    local not_asked=""
    [ -n "$server" ] || not_asked="$not_asked сервер"
    [ -n "$engineer" ] || not_asked="$not_asked личный-номер"
    [ -n "$code" ] || not_asked="$not_asked код"
    if [ -n "$not_asked" ]; then
        echo "codes-server: промпты не спрошены:$not_asked (см. $err)" >&2
        return 1
    fi

    local first
    first="$(printf '%s\n' "$order" | head -n 1)"
    if [ "$first" != "$server" ]; then
        echo "codes-server: первым спрошен не сервер выдачи (см. $err)" >&2
        return 1
    fi
    if [ "$server" -ge "$engineer" ] || [ "$engineer" -ge "$code" ]; then
        echo "codes-server: порядок промптов нарушен (см. $err)" >&2
        return 1
    fi

    echo "prompt-order: server, engineer, code"
}

# Ставит устройству адрес страницы инженера.
#
# Ключ пишется в секцию [codes] поверх прежнего значения. Проверять адрес обязана
# ЗАГРУЗКА конфигурации, поэтому команда ничего не запускает: вердикт даёт
# следующий шаг кейса (`tessera check`), а команда, сама объявившая адрес
# негодным, проверяла бы хелпер.
cmd_set_page_url() {
    local url="${1:-}"
    [ -n "$url" ] || usage_error "usage: codes-server.sh set-page-url <url>"

    require_root
    [ -f "$CONFIG" ] || die "нет конфигурации $CONFIG — подготовка suite не отработала"
    [ -f "$CONFIG_BACKUP" ] || die "секция [codes] не разложена: нужен prepare"

    local staging="$CONFIG.e2e-codes"
    # Прежний ключ снимается только внутри [codes]: секция дописана в конец, и
    # правка «от неё до конца файла» чужих секций не касается.
    sed '/^\[codes\]/,$ { /^page_url = /d; }' "$CONFIG" > "$staging"
    printf 'page_url = "%s"\n' "$url" >> "$staging"
    chmod --reference="$CONFIG" "$staging"
    chown --reference="$CONFIG" "$staging"
    mv -f "$staging" "$CONFIG"

    echo "page-url: $url"
}

