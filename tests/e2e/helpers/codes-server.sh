# Тот же вход, но PAM ведёт sshd, а не драйвер стенда.
#
# Ветвь трогает СИСТЕМНЫЙ стек sshd — иначе проверять нечего: гарантия в том, что
# показ доходит до администратора, у которого физического доступа нет. Прежний
# стек и конфигурация ssh снимаются в резерв и возвращаются cleanup.
#
# Вердикта PAM у ssh нет: клиент видит только свой код возврата. Строка
# `auth: PAM_SUCCESS (0)` здесь — запись этого кода в том же виде, что у
# `pam-drive`, а не процитированный ответ PAM; отказ печатается иначе и кейс на
# него не зеленеет.
cmd_authenticate_over_ssh() {
    local user="${1:-}" level=""
    shift || true
    while [ $# -gt 0 ]; do
        case "$1" in
            --level)
                level="${2:-}"
                shift 2 || usage_error "--level без значения"
                ;;
            *) usage_error "неизвестный аргумент authenticate-over-ssh: $1" ;;
        esac
    done
    [ -n "$user" ] && [ -n "$level" ] \
        || usage_error "usage: codes-server.sh authenticate-over-ssh <user> --level N"

    require_root
    require_tool python3
    require_tool ssh
    load_prepared

    [ "$level" = "$(current_level)" ] \
        || die "ssh-ветвь идёт уровнем сеанса sshd; кейсу нужен $level, а процесс на $(current_level)"

    deploy_ssh_stack

    local transcript="$RUN_DIR/ssh.log" rc=0
    TESSERA_E2E_SERVER_ID="$SERVER_ID" \
    TESSERA_E2E_ENGINEER_ID="$ENGINEER_ID" \
    TESSERA_E2E_DEVICE_PIN="$DEVICE_KEY_PIN" \
    TESSERA_E2E_ISSUE_CMD="$0 issue-code-for-wire" \
        python3 "$(ssh_driver)" "$transcript" \
            ssh -p "$SSH_PORT" \
                -o PreferredAuthentications=keyboard-interactive \
                -o PubkeyAuthentication=no \
                -o StrictHostKeyChecking=no \
                -o UserKnownHostsFile=/dev/null \
                "$user@$SSH_HOST" true || rc=$?

    cat "$transcript" >&2

    if ! grep -qF "$QR_CAPTION_LINE" "$transcript"; then
        echo "codes-server: показ challenge по ssh не дошёл до клиента" >&2
        return 1
    fi

    if [ "$rc" -ne 0 ]; then
        printf 'auth: SSH_FAILED (%d)\n' "$rc"
        return 1
    fi

    echo "auth: PAM_SUCCESS (0)"
}

# Кладёт стек sshd и конфигурацию ssh на время кейса, сняв прежние в резерв.
deploy_ssh_stack() {
    [ -f "$SSH_PAM_BACKUP" ] || cp "$SSH_PAM_SERVICE" "$SSH_PAM_BACKUP"
    cat > "$SSH_PAM_SERVICE" <<'EOF'
# Стек sshd на время кейса QR-003. Кладёт helpers/codes-server.sh, снимает его
# cleanup вместе с резервной копией прежнего стека.
auth       [success=done default=die] pam_tessera.so method=code
account    required                   pam_tessera.so
session    required                   pam_tessera.so
EOF
    chmod 0644 "$SSH_PAM_SERVICE"

    install -d -m 0755 "$(dirname "$SSHD_DROPIN")"
    cat > "$SSHD_DROPIN" <<'EOF'
# На время кейса QR-003: разговор идёт клавиатурно-интерактивным методом через
# PAM, ключи и пароли в нём не участвуют.
UsePAM yes
KbdInteractiveAuthentication yes
PasswordAuthentication no
EOF
    chmod 0644 "$SSHD_DROPIN"
    reload_sshd
}

reload_sshd() {
    if command -v systemctl >/dev/null 2>&1; then
        systemctl reload ssh 2>/dev/null && return 0
        systemctl reload sshd 2>/dev/null && return 0
    fi
    die "нечем перезагрузить sshd: ни ssh, ни sshd не перезагружаются systemctl"
}

# Пишет pty-драйвер разговора и возвращает путь к нему.
#
# Псевдотерминал обязателен: клавиатурно-интерактивный метод ssh спрашивает
# человека, а не поток, и без терминала клиент отказывается спрашивать вовсе.
ssh_driver() {
    local path="$RUN_DIR/ssh-drive.py"
    install -d -m 0700 "$RUN_DIR"
    cat > "$path" <<'PY'
"""Ведёт разговор ssh за инженера и отвечает кодом на показанный challenge."""

import os
import pty
import re
import select
import subprocess
import sys

WIRE = re.compile(r"tessera-codes/v1/signed-challenge;[^\s]+")
TIMEOUT = float(os.environ.get("TESSERA_E2E_SSH_TIMEOUT", "120"))

transcript_path, *command = sys.argv[1:]
answers = [
    os.environ["TESSERA_E2E_SERVER_ID"],
    os.environ["TESSERA_E2E_ENGINEER_ID"],
    os.environ["TESSERA_E2E_DEVICE_PIN"],
]
issue = os.environ["TESSERA_E2E_ISSUE_CMD"].split()

pid, master = pty.fork()
if pid == 0:
    os.execvp(command[0], command)

seen = ""
answered = 0
code_sent = False
with open(transcript_path, "w", encoding="utf-8", errors="replace") as transcript:
    while True:
        ready, _, _ = select.select([master], [], [], TIMEOUT)
        if not ready:
            transcript.write("\n[драйвер: ответа нет дольше таймаута]\n")
            os.kill(pid, 9)
            break
        try:
            chunk = os.read(master, 4096)
        except OSError:
            break
        if not chunk:
            break
        text = chunk.decode("utf-8", errors="replace")
        transcript.write(text)
        transcript.flush()
        seen += text

        # Код считается по показанному challenge и отвечается один раз: бюджет
        # попыток здесь не проверяется, а повторный ответ съел бы промпт
        # следующей фазы.
        found = WIRE.search(seen)
        if found and not code_sent:
            document = found.group(0)
            code = subprocess.run(
                issue + [document], capture_output=True, text=True, check=True
            ).stdout.strip()
            os.write(master, (code + "\n").encode())
            code_sent = True
            seen = ""
            continue

        # Промпт узнаётся по приглашению без перевода строки в конце вывода.
        if not code_sent and seen.rstrip(" ").endswith(":") and answered < len(answers):
            os.write(master, (answers[answered] + "\n").encode())
            answered += 1
            seen = ""

_, status = os.waitpid(pid, 0)
sys.exit(os.waitstatus_to_exitcode(status))
PY
    chmod 0700 "$path"
    printf '%s' "$path"
}

