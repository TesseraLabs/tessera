#!/usr/bin/perl
# overlay-stub.pl — оверлей, который подключился и НИЧЕГО не нарисовал.
#
# Ровно та половина отказа, которую нельзя воспроизвести настоящим оверлеем: он
# либо рисует, либо умирает на открытии дисплея за миллисекунды, и кейс,
# написанный на живом бинаре, ловил бы не поведение модуля, а гонку.
#
# Заглушка подключается к сокету попытки, читает всё, что модуль пришлёт, и
# держит соединение до конца попытки. С точки зрения модуля она неотличима от
# оверлея, у которого не открылся дисплей УЖЕ ПОСЛЕ подключения: процесс жив,
# сокет цел, символа на экране нет.
#
# Perl, а не python: в контейнерном образе стенда его нет, а perl есть, и
# IO::Socket::UNIX входит в поставку самого perl.
#
#   overlay-stub.pl --socket <путь>
#
# Ничего не пишет в сокет: обратного направления у провода нет, и заглушка,
# которая бы что-то отвечала, проверяла бы не тот путь.

use strict;
use warnings;
use IO::Socket::UNIX;

my $socket_path;
while (my $arg = shift @ARGV) {
    if ($arg eq '--socket') {
        $socket_path = shift @ARGV or die "overlay-stub: --socket без пути\n";
    } else {
        die "overlay-stub: неизвестный аргумент $arg\n";
    }
}
die "overlay-stub: не задан --socket\n" unless defined $socket_path;

my $socket = IO::Socket::UNIX->new(
    Type => SOCK_STREAM(),
    Peer => $socket_path,
) or die "overlay-stub: не подключиться к $socket_path: $!\n";

# Прочитанное выбрасывается: заглушка не разбирает кадры и не рисует. Чтение
# нужно затем, чтобы не оставлять записанное модулем в буфере сокета — иначе
# модуль мог бы упереться в переполнение вместо ожидаемого поведения.
my $buffer;
while (1) {
    my $read = sysread($socket, $buffer, 4096);
    # Модуль закрыл сокет (попытка кончилась) либо оборвался — уходим за ним.
    last if !defined $read || $read == 0;
}
exit 0;
