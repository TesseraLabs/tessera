#!/usr/bin/env bash
# build-pam-drive.sh — собирает драйвер PAM-фаз на живой машине.
#
# В контейнерных профилях `pam-drive` вкомпилирован в образ и лежит в PATH —
# там этому действию делать нечего, и оно завершается успехом, ничего не
# трогая. На машине, которую нельзя пересоздать, драйвер собирает подготовка
# прогона: исходник приезжает вместе с остальными хелперами, а бинарь кладётся
# рядом с ними, а не в системные каталоги.
#
# Единственный след вне каталога хелперов — симлинк /usr/local/bin/pam-drive
# (см. ниже, где он ставится): кейсы вызывают драйвер по имени, и без него
# запись кейса пришлось бы делать разной для машины и для контейнера. Снять
# его в teardown нельзя — подготовка выполняется один раз за прогон, и снятый
# после первого же кейса симлинк оборвал бы все следующие.
#
# Идемпотентен: собранный и не устаревший бинарь пересобирать не нужно.

set -euo pipefail

HELPERS="${TESSERA_E2E_HELPERS:-/opt/tessera-e2e/helpers}"
SOURCE="$HELPERS/pam-drive.c"
BINARY="$HELPERS/pam-drive"

# Исходника рядом с хелперами нет — это контейнерный профиль: образ несёт
# готовый драйвер, а .c в него не копируется. Собирать нечего и незачем.
# Проверка идёт именно так, а не по наличию `pam-drive` в PATH: на машине
# симлинк остаётся от прошлого прогона, и шаг по PATH молча пропускал бы
# пересборку устаревшего драйвера.
if [ ! -f "$SOURCE" ]; then
    if command -v pam-drive >/dev/null 2>&1; then
        echo "pam-drive: готовый драйвер образа ($(command -v pam-drive))"
        exit 0
    fi
    echo "build-pam-drive: нет ни исходника $SOURCE, ни готового pam-drive" >&2
    exit 70
fi

# Кейсы вызывают драйвер по имени, как в контейнерных профилях, где он лежит
# в PATH. Симлинк даёт ту же запись кейса на обоих видах окружения; он же —
# единственное, что стенд оставляет в /usr/local, и переживает прогон намеренно
# (см. шапку файла). Ставится на обоих путях: пересборка тут ни при чём, а без
# ссылки собранный драйвер кейсам не виден.
ensure_link() {
    ln -sf "$BINARY" /usr/local/bin/pam-drive
}

if [ -x "$BINARY" ] && [ "$BINARY" -nt "$SOURCE" ]; then
    ensure_link
    echo "pam-drive: уже собран"
    exit 0
fi

command -v gcc >/dev/null 2>&1 || {
    echo "build-pam-drive: не найден gcc" >&2
    exit 70
}
[ -f /usr/include/security/pam_appl.h ] || {
    echo "build-pam-drive: нет заголовков PAM (нужен пакет libpam0g-dev)" >&2
    exit 70
}

gcc -O2 -Wall -Wextra -o "$BINARY" "$SOURCE" -lpam || {
    echo "build-pam-drive: сборка не удалась" >&2
    exit 70
}

ensure_link

echo "pam-drive: собран из $SOURCE"
